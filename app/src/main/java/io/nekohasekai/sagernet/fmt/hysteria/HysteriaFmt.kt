    }
}

fun HysteriaBean.toUri(): String {
    var un = ""
    var pw = ""
    if (protocolVersion == 2) {
        if (authPayload.contains(":")) {
            un = authPayload.substringBefore(":")
            pw = authPayload.substringAfter(":")
        } else {
            un = authPayload
        }
    }
    //
    val builder = linkBuilder()
        .host(serverAddress)
        .port(getFirstPort(serverPorts))
        .username(un)
        .password(pw)
    if (serverPorts.trim().toIntOrNull() == null) {
        builder.addQueryParameter("mport", serverPorts)
    }
    if (name.isNotBlank()) {
        builder.encodedFragment(name.urlSafe())
    }
    if (allowInsecure) {
        builder.addQueryParameter("insecure", "1")
    }
    if (protocolVersion == 1) {
        if (sni.isNotBlank()) {
            builder.addQueryParameter("peer", sni)
        }
        if (authPayload.isNotBlank()) {
            builder.addQueryParameter("auth", authPayload)
        }
        builder.addQueryParameter("upmbps", "$uploadMbps")
        builder.addQueryParameter("downmbps", "$downloadMbps")
        if (alpn.isNotBlank()) {
            builder.addQueryParameter("alpn", alpn)
        }
        if (obfuscation.isNotBlank()) {
            builder.addQueryParameter("obfs", "xplus")
            builder.addQueryParameter("obfsParam", obfuscation)
        }
        when (protocol) {
            HysteriaBean.PROTOCOL_FAKETCP -> {
                builder.addQueryParameter("protocol", "faketcp")
            }

            HysteriaBean.PROTOCOL_WECHAT_VIDEO -> {
                builder.addQueryParameter("protocol", "wechat-video")
            }
        }
    } else {
        if (sni.isNotBlank()) {
            builder.addQueryParameter("sni", sni)
        }
        if (obfuscation.isNotBlank()) {
            builder.addQueryParameter("obfs", hy2ObfsType)
            builder.addQueryParameter("obfs-password", obfuscation)
        }
    }
    return builder.toLink(if (protocolVersion == 2) "hy2" else "hysteria")
}

fun JSONObject.parseHysteria1Json(): HysteriaBean {
    // TODO parse HY2 JSON+YAML
    return HysteriaBean().apply {
        protocolVersion = 1
        serverAddress = optString("server").substringBeforeLast(":")
        serverPorts = optString("server").substringAfterLast(":")
        uploadMbps = getIntNya("up_mbps")
        downloadMbps = getIntNya("down_mbps")
        obfuscation = getStr("obfs")
        getStr("auth")?.also {
            authPayloadType = HysteriaBean.TYPE_BASE64
            authPayload = it
        }
        getStr("auth_str")?.also {
            authPayloadType = HysteriaBean.TYPE_STRING
            authPayload = it
        }
        getStr("protocol")?.also {
            when (it) {
                "faketcp" -> {
                    protocol = HysteriaBean.PROTOCOL_FAKETCP
                }

                "wechat-video" -> {
                    protocol = HysteriaBean.PROTOCOL_WECHAT_VIDEO
                }
            }
        }
        sni = getStr("server_name")
        alpn = getStr("alpn")
        allowInsecure = getBool("insecure")

        streamReceiveWindow = getIntNya("recv_window_conn")
        connectionReceiveWindow = getIntNya("recv_window")
        disableMtuDiscovery = getBool("disable_mtu_discovery")
    }
}

fun HysteriaBean.buildHysteria1Config(port: Int, cacheFile: (() -> File)?): String {
    if (protocolVersion != 1) {
        throw Exception("error version: $protocolVersion")
    }
    return JSONObject().apply {
        put("server", displayAddress())
        when (protocol) {
            HysteriaBean.PROTOCOL_FAKETCP -> {
                put("protocol", "faketcp")
            }

            HysteriaBean.PROTOCOL_WECHAT_VIDEO -> {
                put("protocol", "wechat-video")
            }
        }
        put("up_mbps", uploadMbps)
        put("down_mbps", downloadMbps)
        put(
            "socks5", JSONObject(
                mapOf(
                    "listen" to "$LOCALHOST:$port",
                )
            )
        )
        put("retry", 5)
        put("fast_open", true)
        put("lazy_start", true)
        put("obfs", obfuscation)
        when (authPayloadType) {
            HysteriaBean.TYPE_BASE64 -> put("auth", authPayload)
            HysteriaBean.TYPE_STRING -> put("auth_str", authPayload)
        }
        if (sni.isBlank() && finalAddress == LOCALHOST && !serverAddress.isIpAddress()) {
            sni = serverAddress
        }
        if (sni.isNotBlank()) {
            put("server_name", sni)
        }
        if (alpn.isNotBlank()) put("alpn", alpn)
        if (caText.isNotBlank() && cacheFile != null) {
            val caFile = cacheFile()
            caFile.writeText(caText)
            put("ca", caFile.absolutePath)
        }

        if (allowInsecure) put("insecure", true)
        if (streamReceiveWindow > 0) put("recv_window_conn", streamReceiveWindow)
        if (connectionReceiveWindow > 0) put("recv_window", connectionReceiveWindow)
        if (disableMtuDiscovery) put("disable_mtu_discovery", true)

        put("hop_interval", hopInterval)
    }.toStringPretty()
}

fun isMultiPort(hyAddr: String): Boolean {
    if (!hyAddr.contains(":")) return false
    val p = hyAddr.substringAfterLast(":")
    if (p.contains("-") || p.contains(",")) return true
    return false
}

fun getFirstPort(portStr: String): Int {
    return portStr.substringBefore(",").substringBefore(":").substringBefore("-").trim().toIntOrNull() ?: 443
}

fun HysteriaBean.canUseSingBox(): Boolean {
    if (protocolVersion == 1 && protocol != HysteriaBean.PROTOCOL_UDP) return false
    return true
}

fun buildSingBoxOutboundHysteriaBean(bean: HysteriaBean): SingBoxOptions.SingBoxOption {
    return when (bean.protocolVersion) {
        1 -> SingBoxOptions.Outbound_HysteriaOptions().apply {
            type = "hysteria"
            server = bean.serverAddress
            val port = bean.serverPorts.trim().toIntOrNull()
            require(port == null || port in 1..65535) { "Invalid server port" }
            if (port != null) {
                server_port = port
            } else {
                server_ports = hopPortsToSingboxList(bean.serverPorts)
            }
            hop_interval = "${bean.hopInterval}s"
            up_mbps = bean.uploadMbps
            down_mbps = bean.downloadMbps
            obfs = bean.obfuscation
            disable_mtu_discovery = bean.disableMtuDiscovery
            when (bean.authPayloadType) {
                HysteriaBean.TYPE_BASE64 -> auth = bean.authPayload
                HysteriaBean.TYPE_STRING -> auth_str = bean.authPayload
            }
            if (bean.streamReceiveWindow > 0) {
                recv_window_conn = bean.streamReceiveWindow.toLong()
            }
            if (bean.connectionReceiveWindow > 0) {
                recv_window = bean.connectionReceiveWindow.toLong()
            }
            tls = SingBoxOptions.OutboundTLSOptions().apply {
                if (bean.sni.isNotBlank()) {
                    server_name = bean.sni
                }
                if (bean.alpn.isNotBlank()) {
                    alpn = bean.alpn.listByLineOrComma()
                }
                if (bean.caText.isNotBlank()) {
                    certificate = bean.caText
                }
                insecure = bean.allowInsecure || DataStore.globalAllowInsecure
                enabled = true
            }
        }

        2 -> SingBoxOptions.Outbound_Hysteria2Options().apply {
            type = "hysteria2"
            server = bean.serverAddress
            val port = bean.serverPorts.trim().toIntOrNull()
            require(port == null || port in 1..65535) { "Invalid server port" }
            if (port != null) {
                server_port = port
            } else {
                server_ports = hopPortsToSingboxList(bean.serverPorts)
            }
            hop_interval = "${bean.hopInterval}s"
            up_mbps = bean.uploadMbps
            down_mbps = bean.downloadMbps
            if (bean.obfuscation.isNotBlank()) {
                val kind = bean.hy2ObfsType.ifBlank { "salamander" }
                require(kind in listOf("salamander", "gecko")) { "Invalid Hysteria2 obfuscation type" }
                val options = mutableMapOf<String, Any>("type" to kind, "password" to bean.obfuscation)
                if (kind == "gecko") {
                    fun packetSize(value: String): Int? = value.takeIf { it.isNotBlank() }?.let {
                        (it.toIntOrNull() ?: error("Invalid Gecko packet size")).also { n -> require(n > 0) }
                    }
                    val min = packetSize(bean.hy2GeckoMin)
                    val max = packetSize(bean.hy2GeckoMax)
                    require(min == null || max == null || min <= max) { "Invalid Gecko packet range" }
                    min?.let { options["min_packet_size"] = it }
                    max?.let { options["max_packet_size"] = it }
                }
                _hack_config_map["obfs"] = options
            }
//            disable_mtu_discovery = bean.disableMtuDiscovery
            bean.hy2BbrProfile.takeIf { it.isNotBlank() }?.let {
                require(it in listOf("standard", "conservative", "aggressive")) { "Invalid BBR profile" }
                _hack_config_map["bbr_profile"] = it
            }
            bean.hy2HopIntervalMax.takeIf { it.isNotBlank() }?.let { _hack_config_map["hop_interval_max"] = it }
            bean.hy2Network.trim().takeIf { it.isNotEmpty() }?.let {
                require(it in listOf("tcp", "udp")) { "Invalid Hysteria2 network" }
                _hack_config_map["network"] = it
            }
            bean.hy2IdleTimeout.trim().takeIf { it.isNotEmpty() }?.let { _hack_config_map["idle_timeout"] = it }
            bean.hy2KeepAlive.trim().takeIf { it.isNotEmpty() }?.let { _hack_config_map["keep_alive_period"] = it }
            bean.hy2StreamWindow.trim().takeIf { it.isNotEmpty() }?.let { _hack_config_map["stream_receive_window"] = it }
            bean.hy2ConnectionWindow.trim().takeIf { it.isNotEmpty() }?.let { _hack_config_map["connection_receive_window"] = it }
            bean.hy2MaxStreams.trim().takeIf { it.isNotEmpty() }?.let {
                val value = it.toIntOrNull() ?: error("Invalid max_concurrent_streams")
                require(value > 0) { "max_concurrent_streams must be positive" }
                _hack_config_map["max_concurrent_streams"] = value
            }
            bean.hy2InitialPacket.trim().takeIf { it.isNotEmpty() }?.let {
                val value = it.toIntOrNull() ?: error("Invalid initial_packet_size")
                require(value > 0) { "initial_packet_size must be positive" }
                _hack_config_map["initial_packet_size"] = value
            }
            if (bean.hy2BrutalDebug) _hack_config_map["brutal_debug"] = true
            if (bean.hy2DisableChrome) _hack_config_map["disable_chrome_parrot"] = true
            if (bean.hy2DisablePathMtu) _hack_config_map["disable_path_mtu_discovery"] = true
            bean.hy2Realm.trim().takeIf { it.isNotEmpty() }?.let {
                val realm = com.google.gson.JsonParser.parseString(it).asJsonObject
                require(realm.has("server_url") && realm.has("realm_id") && realm.has("stun_servers")) { "Realm requires server_url, realm_id and stun_servers" }
                _hack_config_map["realm"] = realm
            }
            password = bean.authPayload
//            if (bean.streamReceiveWindow > 0) {
//                recv_window_conn = bean.streamReceiveWindow.toLong()
//            }
//            if (bean.connectionReceiveWindow > 0) {
//                recv_window_conn = bean.connectionReceiveWindow.toLong()
//            }
            tls = SingBoxOptions.OutboundTLSOptions().apply {
                if (bean.sni.isNotBlank()) {
                    server_name = bean.sni
                }
                alpn = listOf("h3")
                if (bean.caText.isNotBlank()) {
                    certificate = bean.caText
                }
                insecure = bean.allowInsecure || DataStore.globalAllowInsecure
                enabled = true
            }
        }

        else -> error("error_version $bean.protocolVersion")
    }
}

fun hopPortsToSingboxList(s: String): List<String> {
    return s.split(",").map { entry ->
        val parts = entry.trim().replace("-", ":").split(":")
        require(parts.size in 1..2) { "Invalid port range" }
        val first = parts.first().trim().toIntOrNull() ?: error("Invalid port")
        val last = parts.last().trim().toIntOrNull() ?: error("Invalid port")
        require(first in 1..65535 && last in first..65535) { "Invalid port range" }
        "$first:$last"
    }
}
